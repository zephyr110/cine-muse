/** 8 段黄金表：镜头尖 [0,0,0.07] → 远帧（半宽 0.56 / 半高 0.315 @ depth 1.82） */
const FRUSTUM_LINES: [WirePoint, WirePoint][] = [
  [[0, 0, 0.07], [-0.56, 0.315, 1.82]],
  [[0, 0, 0.07], [0.56, 0.315, 1.82]],
  [[0, 0, 0.07], [0.56, -0.315, 1.82]],
  [[0, 0, 0.07], [-0.56, -0.315, 1.82]],
  [[-0.56, 0.315, 1.82], [0.56, 0.315, 1.82]],
  [[0.56, 0.315, 1.82], [0.56, -0.315, 1.82]],
  [[0.56, -0.315, 1.82], [-0.56, -0.315, 1.82]],
  [[-0.56, -0.315, 1.82], [-0.56, 0.315, 1.82]],
]

describe("previs-rig-geometry（机位 rig 线框锁定）", () => {
  it("cameraBodyWireframeLines：20 线逐点锁定（盒体 12 + 镜头倒锥 6 + 双圆盘 2）", () => {
    const lines = cameraBodyWireframeLines()
    expect(lines).toHaveLength(20)
    expect(lines.map((line) => line.map(snapPoint))).toEqual(BODY_LINES)
  })

  it("cameraFrustumLines：8 段逐点锁定（镜头尖 → 16:9 远帧）", () => {
    const lines = cameraFrustumLines()
    expect(lines).toHaveLength(8)
    expect(lines.map(([a, b]) => [snapPoint(a), snapPoint(b)])).toEqual(FRUSTUM_LINES)
  })

  it("cameraHitArea：命中盒尺寸/中心锁定（包围盒 + padding）", () => {
    const { args, position } = cameraHitArea()
    expect([snapPoint(args), snapPoint(position)]).toEqual([
      [0.295, 0.4175, 0.547],
      [0, 0.07875, -0.1435],
    ])
  })

  it("颜色/透明度/缩放常量锁定（REF VIEWPORT_CAMERA_*）", () => {
    expect(CAM_SCALE).toBe(0.35)
    expect(CAM_LINE_COLOR).toBe(0xa9d8ff)
    expect(CAM_LINE_OPACITY).toBe(0.92)
  })
})
